#!/usr/bin/env bash
#
# Builds the modules a kernel config fragment enables, from the kernel's own
# sources, against a dev kit.
#
# Usage: build-fragment.sh <devkit> <fragment> <work dir> <modules out dir>
#
# Environment: CROSS_COMPILE, NERVES_LAYER_SOURCE_CACHE (kernel checkouts).
#
# 1. Kconfig resolves the fragment against the system's config, with and
#    without it, and check-config.sh vets the difference.
# 2. Each makefile gating a changed option is evaluated by make
#    (kbuild-eval.mk) with and without the changes; the new modules and their
#    objects are the difference.
# 3. Only those objects' sources, the headers they include by relative path
#    and their directories' makefiles are fetched and copied, and each
#    directory gets a Kbuild that includes the kernel's makefile and keeps
#    only the new modules.

set -euo pipefail

SCRIPTS=$(dirname "$(realpath "$0")")
source "$SCRIPTS/lib.sh"

[[ $# -eq 4 ]] || die "usage: build-fragment.sh <devkit> <fragment> <work dir> <modules out dir>"
DEVKIT=$1 FRAGMENT=$2 WORK=$3 OUT=$4

SRC=$(kernel_checkout "$DEVKIT" "$NERVES_LAYER_SOURCE_CACHE")
ARCH=$(devkit_env "$DEVKIT" KERNEL_ARCH)

olddefconfig() { # <out dir> <config file>...
    local out=$1
    shift
    rm -rf "$out"
    mkdir -p "$out"
    cat "$@" > "$out/.config"
    make -s -C "$SRC" O="$out" ARCH="$ARCH" CROSS_COMPILE="$CROSS_COMPILE" olddefconfig
}

olddefconfig "$WORK/kconfig-base" "$DEVKIT/.config"
olddefconfig "$WORK/kconfig" "$DEVKIT/.config" "$FRAGMENT"

UNMET=$(grep -E '^CONFIG_[A-Za-z0-9_]+=' "$FRAGMENT" | grep -vxFf "$WORK/kconfig/.config" || true)
[[ -z $UNMET ]] || die "Kconfig didn't accept these options, usually because of unmet dependencies:
$UNMET"

CHANGES=$("$SCRIPTS/check-config.sh" "$DEVKIT/.config" "$WORK/kconfig-base/.config" \
    "$WORK/kconfig/.config" "$DEVKIT/kernel-config-refs" "$SRC")
sed 's/^/    /' <<< "$CHANGES" >&2

mapfile -t OVERRIDES <<< "$CHANGES"
MODULE_OPTIONS=$(sed -n 's/^CONFIG_\([A-Za-z0-9_]*\)=m$/\1/p' <<< "$CHANGES")

eval_dir() { # <dir> [CONFIG_<NAME>=<value>...]
    local dir=$1
    shift
    make -s -f "$SCRIPTS/kbuild-eval.mk" DEVKIT="$DEVKIT" SRC="$SRC" DIR="$dir" "$@" | LC_ALL=C sort
}

# "<dir> <module>.o <object>..." for every module the changes add.
MODULES=$(
    for name in $MODULE_OPTIONS; do
        grep -rlF --include=Makefile --include=Kbuild "obj-\$(CONFIG_$name)" "$SRC" || true
    done | xargs -r -n 1 dirname | LC_ALL=C sort -u | while read -r path; do
        dir=${path#"$SRC"/}
        LC_ALL=C comm -13 <(eval_dir "$dir") <(eval_dir "$dir" "${OVERRIDES[@]}") | sed "s|^|$dir |"
    done
)
[[ -n $MODULES ]] || die "the kernel config fragment doesn't enable any module"

SOURCES=()
while read -r dir _module objects; do
    for object in $objects; do
        base="$dir/${object%.o}"
        if kernel_has "$SRC" "$base.c"; then
            SOURCES+=("$base.c")
        elif kernel_has "$SRC" "$base.S"; then
            SOURCES+=("$base.S")
        else
            die "no source for $dir/$object in the kernel tree"
        fi
    done
done <<< "$MODULES"
kernel_add "$SRC" "${SOURCES[@]}"

# Headers included as "relative/path.h", or as <../path.h> against include/,
# live next to the drivers rather than in the dev kit.
FILES=("${SOURCES[@]}")
PENDING=("${SOURCES[@]}")
while [[ ${#PENDING[@]} -gt 0 ]]; do
    FOUND=()
    for file in "${PENDING[@]}"; do
        while read -r kind target; do
            case $kind in
                '"') candidate=$(realpath -m --relative-to="$SRC" "$SRC/$(dirname "$file")/$target") ;;
                '<') candidate=$(realpath -m --relative-to="$SRC" "$SRC/include/$target") ;;
            esac
            if [[ " ${FILES[*]} ${FOUND[*]} " != *" $candidate "* ]] && kernel_has "$SRC" "$candidate"; then
                FOUND+=("$candidate")
            fi
        done < <(sed -nE 's/^[[:space:]]*#[[:space:]]*include[[:space:]]*"([^"]+)".*/" \1/p;
                          s/^[[:space:]]*#[[:space:]]*include[[:space:]]*<(\.\.\/[^>]+)>.*/< \1/p' "$SRC/$file")
    done
    if [[ ${#FOUND[@]} -gt 0 ]]; then
        kernel_add "$SRC" "${FOUND[@]}"
        FILES+=("${FOUND[@]}")
    fi
    PENDING=("${FOUND[@]}")
done

BUILD="$WORK/kbuild"
rm -rf "$BUILD"
mkdir -p "$BUILD/include"
(cd "$SRC" && cp --parents "${FILES[@]}" "$BUILD")

: > "$BUILD/Kbuild"
for dir in $(cut -d' ' -f1 <<< "$MODULES" | LC_ALL=C sort -u); do
    makefile="$SRC/$dir/Kbuild"
    [[ -f $makefile ]] || makefile="$SRC/$dir/Makefile"
    cp "$makefile" "$BUILD/$dir/Makefile.kernel"
    cat > "$BUILD/$dir/Kbuild" <<EOF
# Generated by nerves_layer: the kernel's makefile for this directory,
# limited to the modules the layer adds.
include \$(src)/Makefile.kernel
obj-m := \$(filter $(awk -v d="$dir" '$1 == d { print $2 }' <<< "$MODULES" | xargs),\$(obj-m))
obj-y :=
EOF
    echo "obj-m += $dir/" >> "$BUILD/Kbuild"
done

# The dev kit's autoconf.h describes the system's config; the C code sees
# the changed options through these defines.
DEFINES=$(sed -E 's/^(CONFIG_[A-Za-z0-9_]+)=m$/-D\1_MODULE=1/; s/^(CONFIG_[A-Za-z0-9_]+)=y$/-D\1=1/; s/^(CONFIG_[A-Za-z0-9_]+)=(.*)$/-D\1=\2/' <<< "$CHANGES" | xargs)

"$SCRIPTS/build-modules.sh" "$DEVKIT" "$BUILD" "$OUT" \
    "KCFLAGS=-idirafter $BUILD/include $DEFINES" "${OVERRIDES[@]}"
